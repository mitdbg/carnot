QUERY_STRUCTURE_GUIDANCE = """Queries are generated by composing category names with set operations such as intersection, union, and difference, then rewriting the result as a natural-language query.

The query will follow one of these templates:
['_', '_ or _', '_ or _ or _', '_ that are also _',
 '_ that are also _ but not _',
 '_ that are also both _ and _',
 '_ that are not _']"""

FILTER_SELECTION_INSTRUCTIONS = f"""{QUERY_STRUCTURE_GUIDANCE}

Your task is to select metadata filters that can help pre-filter for this query.

Analyze the query's constraints and select filters that can confidently express at least some of them. This is recall-oriented pruning; vector search handles final ranking.

Return only a JSON array of filter names. If no filter clearly applies, return []."""

WHERE_PLANNING_INSTRUCTIONS = f"""{QUERY_STRUCTURE_GUIDANCE}

Your task is to map the query to a ChromaDB where-clause using the filter catalog.
This is RECALL-ORIENTED pruning — the filter's only job is to avoid losing relevant documents. Vector search handles final ranking and precision.

Rules:
1. ALWAYS use $or as the top-level combinator. Flatten all relevant tags into a single $or list. Do NOT use $and to combine different constraints — metadata is incomplete and requiring ALL constraints filters out relevant documents.
2. Include every catalog tag that MIGHT match a relevant document. Cast a wide net. It is much better to include 200 candidates that contain all gold documents than to return 5 candidates that miss half of them.
3. For queries with exclusion ("not _", "excluding _", "but not _"), still use $or for the positive constraints. Ignore the exclusion for filtering — vector search handles it.
4. If no catalog entry clearly applies, return null.
5. Use only filters and values present in the catalog.

Return only JSON, or null if no useful filter applies."""

